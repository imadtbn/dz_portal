import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runsOn,recordsAtStation,eligible} from '../assets/js/sntf-trains/engine.js';
const load=name=>JSON.parse(readFileSync('assets/data/sntf/'+name+'.json','utf8'));
const trips=load('trips').trips,calendars=load('calendars').calendars;
const byId=new Map(trips.map(t=>[t.trip_id,t]));
const config={calendars,exceptions:[],holidays:[]};
const batna=byId.get('photo-east-batna-agha');
assert.equal(batna.stop_times[4].arrival,'24:28','Batna return crosses midnight');
assert(runsOn(batna,'2026-09-29',calendars));
const annaba=byId.get('photo-east-agha-annaba');
assert(!runsOn(annaba,'2026-09-29',calendars),'Contradictory Annaba calendars must not create a scheduled arrival');
const bejaia=byId.get('photo-east-agha-bejaia');
assert(!runsOn(bejaia,'2026-09-29',calendars),'Unspecified service days must not create scheduled departures');
const te=byId.get('photo-east-agha-tebessa');
assert(runsOn(te,'2026-09-29',calendars),'Tuesday outbound Tebessa service');
assert(!runsOn(te,'2026-09-30',calendars),'No invented Wednesday outbound Tebessa service');
const events=recordsAtStation(eligible(trips),'agha','departure','2026-09-29',config,new Date('2026-09-29T18:30:00+01:00'));
assert(events.some(e=>e.trip.trip_id==='photo-east-agha-tebessa'));
assert(!events.some(e=>e.trip.trip_id==='photo-east-agha-annaba'));
assert(!events.some(e=>e.trip.trip_id==='photo-east-agha-bejaia'));
console.log('SNTF East PASS: overnight times, published operating days, unresolved calendar suppression.');
